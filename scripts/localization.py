#!/usr/bin/env python3
"""Localization tooling for SubTitle TransFixer.

  python3 scripts/localization.py extract            # print all UI strings as JSON
  python3 scripts/localization.py generate sv.json   # write Strings+sv.swift from a JSON table
  python3 scripts/localization.py check              # verify every table (exit code 1 on problems)

User-facing strings are written in English and wrapped in L("…"). The English
text is the key. Translations live in Sources/SubTitleTransFixer/Localization/
Strings+<code>.swift as Swift dictionaries generated from JSON.
"""
import json, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "Sources", "SubTitleTransFixer")
LOC = os.path.join(SRC, "Localization")
LANGS = {"sv": "SV", "nb": "NB", "da": "DA", "fi": "FI", "is": "IS"}
LANG_NAMES = {"sv": "Swedish", "nb": "Norwegian (Bokmål)", "da": "Danish", "fi": "Finnish", "is": "Icelandic"}

STRING = r'"((?:[^"\\\n]|\\.)*)"'
CALL = re.compile(r'\bL\(\s*' + STRING)
CHOICE_KEY = re.compile(r'\bkey:\s*' + STRING)
PLACEHOLDER = re.compile(r'\{\d+\}')


def unescape(s):
    out, i = [], 0
    while i < len(s):
        c = s[i]
        if c == "\\" and i + 1 < len(s):
            n = s[i + 1]
            out.append({"n": "\n", "t": "\t", '"': '"', "\\": "\\", "'": "'", "0": "\0"}.get(n, "\\" + n))
            i += 2
        else:
            out.append(c)
            i += 1
    return "".join(out)


def escape(s):
    return s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\t", "\\t")


def extract():
    keys, where = [], {}
    for dirpath, _, files in os.walk(SRC):
        if os.path.abspath(dirpath) == os.path.abspath(LOC):
            continue
        for f in sorted(files):
            if not f.endswith(".swift"):
                continue
            path = os.path.join(dirpath, f)
            text = open(path, encoding="utf-8").read()
            found = [m.group(1) for m in CALL.finditer(text)]
            if f == "AppSettings.swift":
                found += [m.group(1) for m in CHOICE_KEY.finditer(text)]
            for raw in found:
                if "\\(" in raw:
                    sys.exit(f"{path}: string interpolation inside L(): {raw!r} – use {{0}} placeholders")
                k = unescape(raw)
                if k not in where:
                    keys.append(k)
                    where[k] = os.path.relpath(path, ROOT)
    return keys, where


def table_path(code):
    return os.path.join(LOC, f"Strings+{code}.swift")


def read_table(code):
    path = table_path(code)
    if not os.path.exists(path):
        return None, []
    text = open(path, encoding="utf-8").read()
    pairs = re.findall(r'^\s*' + STRING + r'\s*:\s*' + STRING + r',\s*$', text, re.M)
    table, dupes = {}, []
    for k, v in pairs:
        k, v = unescape(k), unescape(v)
        if k in table:
            dupes.append(k)
        table[k] = v
    return table, dupes


def generate(json_path):
    code = os.path.basename(json_path).split(".")[0]
    if code not in LANGS:
        sys.exit(f"unknown language code {code!r}")
    data = json.load(open(json_path, encoding="utf-8"))
    keys, _ = extract()
    lines = [
        "// Generated by scripts/localization.py from a JSON table – edit the JSON and regenerate.",
        f"// {LANG_NAMES[code]} translations of the user interface. Keys are the English texts.",
        "",
        f"let strings{LANGS[code]}: [String: String] = [",
    ]
    for k in keys:  # source order, only keys that are in use
        if k in data and data[k].strip():
            lines.append(f'    "{escape(k)}": "{escape(data[k])}",')
    lines.append("]")
    open(table_path(code), "w", encoding="utf-8").write("\n".join(lines) + "\n")
    print(f"wrote {table_path(code)}")


def check():
    keys, where = extract()
    ok = True
    for code in LANGS:
        table, dupes = read_table(code)
        if table is None:
            print(f"[{code}] missing table {table_path(code)}")
            ok = False
            continue
        missing = [k for k in keys if k not in table]
        unused = [k for k in table if k not in where]
        bad = [k for k in keys if k in table
               and sorted(PLACEHOLDER.findall(k)) != sorted(PLACEHOLDER.findall(table[k]))]
        for k in dupes:
            print(f"[{code}] DUPLICATE key (would crash at launch): {k!r}")
        for k in missing:
            print(f"[{code}] missing: {k!r}  ({where[k]})")
        for k in bad:
            print(f"[{code}] placeholders differ: {k!r} -> {table[k]!r}")
        for k in unused:
            print(f"[{code}] unused: {k!r}")
        if dupes or missing or bad:
            ok = False
        print(f"[{code}] {len(keys) - len(missing)}/{len(keys)} translated")
    return ok


if __name__ == "__main__":
    cmd = sys.argv[1] if len(sys.argv) > 1 else "check"
    if cmd == "extract":
        keys, where = extract()
        json.dump({k: where[k] for k in keys}, sys.stdout, ensure_ascii=False, indent=1)
        print()
    elif cmd == "generate":
        for p in sys.argv[2:]:
            generate(p)
    elif cmd == "check":
        sys.exit(0 if check() else 1)
    else:
        sys.exit(__doc__)
